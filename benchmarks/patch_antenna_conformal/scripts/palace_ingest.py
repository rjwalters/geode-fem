#!/usr/bin/env python3
"""Ingest Palace driven sweeps of the conformal patch (issue #1126, X1).

Reads each run's `port-S.csv` (Palace's S-parameter output: frequency in GHz,
|S11| in dB, arg S11 in degrees) and its log (problem size, wall time, peak
RSS from `/usr/bin/time -v`), and writes one TOML with, per run:

* the |S11| dip: the sampled minimum refined by a parabola through it and its
  two neighbours (in dB, on the uniform frequency grid);
* the -10 dB band: the contiguous run around the dip, crossings interpolated
  linearly in dB, its width and its overlap with the 2.400-2.4835 GHz ISM
  band;
* the worst |S11| over the 9 in-band points geode verifies (2.400 to 2.4835
  GHz in 10.4375 MHz steps), interpolated linearly in dB;
* the problem size and cost.

Usage:
  python3 palace_ingest.py --out SUMMARY.toml RUN_DIR:NAME[:DESC] ...

RUN_DIR holds `port-S.csv` (Palace's `Problem.Output`) and NAME.log the
captured stdout+stderr.
"""

from __future__ import annotations

import argparse
import csv
import math
import re
from pathlib import Path

BAND = (2.4, 2.4835)


def read_sparams(path: Path):
    rows = []
    with path.open() as fh:
        reader = csv.reader(fh)
        header = [h.strip() for h in next(reader)]
        i_f = 0
        i_db = next(i for i, h in enumerate(header) if "S[1][1]" in h and "dB" in h)
        i_arg = next(i for i, h in enumerate(header) if "S[1][1]" in h and "arg" in h)
        for r in reader:
            if not r or not r[0].strip():
                continue
            rows.append((float(r[i_f]), float(r[i_db]), float(r[i_arg])))
    rows.sort()
    return header, rows


def dip(rows):
    k = min(range(len(rows)), key=lambda i: rows[i][1])
    f, d = rows[k][0], rows[k][1]
    if 0 < k < len(rows) - 1:
        (f0, d0, _), (f1, d1, _), (f2, d2, _) = rows[k - 1], rows[k], rows[k + 1]
        den = (f0 - f1) * (f0 - f2) * (f1 - f2)
        a = (f2 * (d1 - d0) + f1 * (d0 - d2) + f0 * (d2 - d1)) / den
        b = (f2 * f2 * (d0 - d1) + f1 * f1 * (d2 - d0) + f0 * f0 * (d1 - d2)) / den
        if a > 0:
            f = -b / (2 * a)
            c = d1 - a * f1 * f1 - b * f1
            d = a * f * f + b * f + c
    return f, d, k, rows[k][0] in (rows[0][0], rows[-1][0])


def band(rows, k):
    if rows[k][1] > -10.0:
        return None

    def cross(i, j):
        (fa, da, _), (fb, db, _) = rows[i], rows[j]
        return fa + (-10.0 - da) * (fb - fa) / (db - da)

    lo = hi = None
    i = k
    while i > 0 and rows[i - 1][1] <= -10.0:
        i -= 1
    if i > 0:
        lo = cross(i - 1, i)
    j = k
    while j < len(rows) - 1 and rows[j + 1][1] <= -10.0:
        j += 1
    if j < len(rows) - 1:
        hi = cross(j, j + 1)
    return lo, hi


def interp_db(rows, f):
    for (f0, d0, _), (f1, d1, _) in zip(rows, rows[1:]):
        if f0 <= f <= f1 + 1e-12:
            return d0 + (f - f0) * (d1 - d0) / (f1 - f0)
    return None


def log_info(path: Path) -> dict:
    out = {}
    if not path.exists():
        return out
    text = path.read_text(errors="replace")
    m = re.findall(r"ND \(p = (\d+)\).*?:\s*([\d,]+)", text)
    if m:
        out["nd_order"] = int(m[-1][0])
        out["n_dofs"] = int(m[-1][1].replace(",", ""))
    m = re.search(r"Elapsed \(wall clock\) time \(h:mm:ss or m:ss\):\s*([\d:.]+)", text)
    if m:
        parts = [float(p) for p in m.group(1).split(":")]
        sec = 0.0
        for p in parts:
            sec = sec * 60 + p
        out["wall_s"] = sec
    m = re.search(r"Maximum resident set size \(kbytes\):\s*(\d+)", text)
    if m:
        out["max_rss_gib_one_rank"] = int(m.group(1)) / 1024**2
    # PROM greedy: "n = 10, error = ..." counts the HDM sample vectors (two
    # per solved frequency); "Greedy iteration" lines are the HDM solves after
    # the two band-edge samples.
    m = re.findall(r"^\s*n = (\d+), error = ([\d.e+-]+)", text, flags=re.M)
    if m:
        out["prom_n_samples"] = int(m[-1][0])
        out["prom_error"] = float(m[-1][1])
    m = re.search(r"Total offline phase elapsed time:\s*([\d.e+-]+)", text)
    if m:
        out["prom_offline_s"] = float(m.group(1))
    return out


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("runs", nargs="+")
    args = ap.parse_args()
    lines = [
        "# Auto-generated by benchmarks/patch_antenna_conformal/scripts/palace_ingest.py",
        "# from the Palace runs listed below (issue #1126, X1). Do NOT edit by hand.",
        "",
        "[meta]",
        'description = "Independent reference: Palace driven sweeps of the conformal patch on '
        "geode's own meshes (MSH 2.2 written by patch_conformal_nested_dof --write-mesh), with "
        "the UPML shell treated as air and a first-order absorbing boundary on the outer wall. "
        "Dip = parabola through the sampled |S11| minimum (dB) and its neighbours; -10 dB band "
        'crossings interpolated linearly in dB; worst_in_band over the 9 geode verify points."',
        f"band_f_ghz = [{BAND[0]}, {BAND[1]}]",
        "",
    ]
    for spec in args.runs:
        parts = spec.split(":")
        run_dir, name = Path(parts[0]), parts[1]
        desc = parts[2] if len(parts) > 2 else ""
        header, rows = read_sparams(run_dir / "port-S.csv")
        f_dip, d_dip, k, on_edge = dip(rows)
        bd = band(rows, k)
        verify = [BAND[0] + (BAND[1] - BAND[0]) * i / 8 for i in range(9)]
        worst = [interp_db(rows, f) for f in verify]
        info = log_info(run_dir.parent.parent / f"{name}.log")
        lines.append(f"[run.{name}]")
        if desc:
            lines.append(f"description = {toml_str(desc)}")
        lines.append(f"grid_ghz = [{rows[0][0]:.4f}, {rows[-1][0]:.4f}]")
        lines.append(f"n_points = {len(rows)}")
        lines.append(f"dip_f_ghz = {f_dip:.6f}")
        lines.append(f"dip_db = {d_dip:.4f}")
        lines.append(f"dip_on_grid_edge = {str(on_edge).lower()}")
        if bd is not None:
            lo, hi = bd
            if lo is not None:
                lines.append(f"band_lo_ghz = {lo:.6f}")
            if hi is not None:
                lines.append(f"band_hi_ghz = {hi:.6f}")
            if lo is not None and hi is not None:
                lines.append(f"bandwidth_mhz = {1e3 * (hi - lo):.3f}")
                cov = max(0.0, min(hi, BAND[1]) - max(lo, BAND[0]))
                lines.append(f"ism_coverage_mhz = {1e3 * cov:.3f}")
                lines.append(f"ism_coverage_frac = {cov / (BAND[1] - BAND[0]):.4f}")
                lines.append(
                    f"centring_mhz = {1e3 * (0.5 * (BAND[0] + BAND[1]) - 0.5 * (lo + hi)):.3f}"
                )
        if all(w is not None for w in worst):
            lines.append(f"worst_in_band_db = {max(worst):.4f}")
        for k2, v in info.items():
            lines.append(f"{k2} = {v:.3f}" if isinstance(v, float) else f"{k2} = {v}")
        lines.append("")
    Path(args.out).write_text("\n".join(lines))
    print(args.out)


if __name__ == "__main__":
    main()
