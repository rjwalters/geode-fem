#!/usr/bin/env python3
"""Per-evaluation cost and cross-evaluation of designs (issue #1130).

Drives one `patch_conformal_nested_dof --eval-server` (geode's own forward
solver, or Palace with `--palace-eval`) and, for every `--design`, asks for

* the band evaluation (`f`: the 5 objective points, worst-of-band and the
  soft-max objective) and
* the 9 in-band verification points (`v`),

and, with `--grad`, the forward + adjoint band evaluation (`g`, geode only).
`--repeat-x0 K` first evaluates the initial patch (x = 0) K times, forward
(and with `--grad` also adjoint), as the per-evaluation cost sample. Every
request's wall time is recorded, so the TOML holds both the cross-check
numbers and the cost per evaluation on this host.

A design is `NAME=PATH` where PATH is a results TOML with
`[shape].design_vector` (geode's or `palace_loop_prima.py`'s), or `NAME=0`
for the initial patch.

Usage:
  palace_loop_xeval.py --exe BIN --out OUT.toml --solver geode|palace \\
      [--repeat-x0 3] [--grad] [--host "..."] [--design NAME=PATH ...] \\
      -- <patch_conformal_nested_dof flags>
"""

from __future__ import annotations

import argparse
import math
import os
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from palace_loop_prima import Server  # noqa: E402


def design(spec: str, n: int):
    name, _, path = spec.partition("=")
    if path == "0":
        return name, [0.0] * n, "x = 0"
    d = tomllib.loads(Path(path).read_text())
    x = d["shape"]["design_vector"]
    assert len(x) == n, f"{path}: {len(x)} design values, server has {n}"
    return name, x, os.path.basename(path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--exe", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--solver", choices=["geode", "palace"], required=True)
    ap.add_argument("--repeat-x0", type=int, default=0)
    ap.add_argument("--grad", action="store_true")
    ap.add_argument("--host", default="")
    ap.add_argument("--design", action="append", default=[])
    ap.add_argument("--server-log", default="xeval_server.log")
    ap.add_argument("flags", nargs=argparse.REMAINDER)
    a = ap.parse_args()
    flags = a.flags[1:] if a.flags and a.flags[0] == "--" else a.flags
    srv = Server(a.exe, flags, a.server_log)
    n = srv.hello["n_dofs"]
    assert bool(srv.hello["external"]) == (a.solver == "palace"), srv.hello
    t = [
        "# Auto-generated by benchmarks/patch_antenna_conformal/scripts/palace_loop_xeval.py",
        "# (issue #1130). Do NOT edit by hand.\n",
        "[meta]",
        f'solver = "{a.solver}"',
        f'palace_np = {int(os.environ.get("PALACE_NP", "16")) if a.solver == "palace" else 0}',
        f'host = "{a.host}"',
        "band_points_ghz = [" + ", ".join(f"{float(f):.6f}" for f in srv.hello["band_ghz"]) + "]",
        'cost_rule = "one solve = one frequency with one factorization (geode) or one Palace '
        'driven solve (Palace); a band evaluation is 5 solves; wall_s is the whole request '
        '(mesh morph and, for Palace, the MSH 2.2 write, docker and MPI start-up and mesh '
        'partitioning)"',
        "",
    ]
    x0 = [0.0] * n
    for k in range(a.repeat_x0):
        kinds = ["f"] + (["g"] if a.grad else [])
        for kind in kinds:
            r = srv.ask(kind, x0)
            t += [
                "[[cost.sample]]",
                f'kind = "{ {"f": "forward", "g": "forward_adjoint"}[kind] }"',
                f"repeat = {k}",
                f"wall_s = {r['wall_s']:.3f}",
                f"worst_db = {r['worst_db']:.6f}",
                "",
            ]
            print(f"  cost x0 {kind} #{k}: {r['wall_s']:.1f} s, worst {r['worst_db']:.3f} dB",
                  file=sys.stderr, flush=True)
    for spec in a.design:
        name, x, src = design(spec, n)
        rf = srv.ask("f", x)
        rv = srv.ask("v", x)
        t += ["[[design]]", f'name = "{name}"', f'source = "{src}"',
              f"min_vol_ratio = {rf['min_vol_ratio']:.6f}", f"feasible = {str(rf['feasible']).lower()}"]
        if rf["feasible"]:
            t += [f"band_worst_db = {rf['worst_db']:.6f}", f"objective = {rf['objective']:.9e}",
                  "band_db = [" + ", ".join(f"{10 * math.log10(g):.4f}" for g in rf["g"]) + "]",
                  f"band_wall_s = {rf['wall_s']:.3f}"]
        vdb = [10 * math.log10(g) for g in rv["g"]]
        t += ["verify_f_ghz = [" + ", ".join(f"{f:.6f}" for f in rv["f_ghz"]) + "]",
              "verify_db = [" + ", ".join(f"{v:.4f}" for v in vdb) + "]",
              f"verify_worst_db = {max(vdb):.6f}", f"verify_wall_s = {rv['wall_s']:.3f}", ""]
        print(f"  {name}: band worst {rf.get('worst_db', float('nan')):.3f} dB, "
              f"verify worst {max(vdb):.3f} dB", file=sys.stderr, flush=True)
    srv.close()
    Path(a.out).write_text("\n".join(t))
    print(f"palace_loop_xeval: {a.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
