#!/usr/bin/env python3
"""Merge the #520 on-box sweep outputs into one table (stdout, TOML).

usage: summarize_520.py <sweep-dir>

<sweep-dir> holds box_sweep.sh outputs (<leg>.stdout / .time / .gpumem / .meta)
and palace/ (box_palace_driven.sh outputs). Each leg's .stdout is the
gpu_driven_scaling test stdout; the TOML fragment between the "fragment"
marker lines is parsed with tomllib. For capped (GEODE_SCALING_ITER_MAX)
legs the cell is a DNF; this script prints the raw capped attempt times
(dnf_attempt_s, iterations) for the cap300 and cap1 legs. The per-iteration
costs recorded in results_large_a100.toml are NOT dnf_attempt_s / iterations
(that would include the per-omega prepare_at setup and JIT/autotune). They are
setup-subtracted net values, s_per_iter_net = (t_cap300 - t_cap1) / 299, and
the GPU/CPU per-iteration ratios. Both were computed by hand from this
script's output (the cap legs run the same sizes in the same order per
process, so setup cancels in the subtraction). Pure stdlib, no fitting.
"""
import pathlib
import re
import sys
import tomllib

d = pathlib.Path(sys.argv[1])


def fragment(path):
    txt = path.read_text()
    # A leg killed mid-run (partial/) has no end marker: parse to EOF, keeping
    # only complete [[cell]] tables (a truncated trailing table is dropped).
    m = re.search(r"# ---- gpu_driven_scaling TOML fragment.*?\n(.*?)(?:# ---- end fragment ----|\Z)", txt, re.S)
    if not m:
        return []
    body = m.group(1)
    try:
        return tomllib.loads(body).get("cell", [])
    except tomllib.TOMLDecodeError:
        return tomllib.loads(body[: body.rfind("[[cell]]")]).get("cell", [])


def time_v(path):
    out = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        if "Maximum resident set size" in line:
            out["max_rss_kb"] = int(line.split()[-1])
        if "Elapsed (wall clock)" in line:
            out["wall"] = line.split()[-1]
    return out


def gpu_peak(path):
    if not path.exists():
        return None
    vals = [int(l.split(",")[0]) for l in path.read_text().splitlines() if l.strip()]
    return max(vals) if vals else None


rows = []
for t in sorted(d.glob("*.stdout")) + sorted(d.glob("partial/*.stdout")):
    leg = t.stem if t.parent == d else f"partial/{t.stem}"
    tv = time_v(t.parent / f"{t.stem}.time")
    gp = gpu_peak(t.parent / f"{t.stem}.gpumem")
    for c in fragment(t):
        c = dict(c)
        c["leg"] = leg
        c["leg_max_rss_kb"] = tv.get("max_rss_kb")
        c["leg_gpu_peak_mib"] = gp
        rows.append(c)

print("# ---- generated by benchmarks/gpu_driven_scaling/summarize_520.py ----")
for c in sorted(rows, key=lambda c: (c["size_n"], c["config"], c["device"])):
    if c.get("converged") is False and "dnf_attempt_s" in c:
        kind = "capped" if c["iterations"] < 20000 else "dnf"
        t = c["dnf_attempt_s"]
        per = t / c["iterations"]
    else:
        kind = "full"
        t = c.get("warmup_solve_s")
        if c.get("solve_reps_ok", 0) and c.get("solve_only_s") == c.get("solve_only_s"):
            t_rep = c["solve_only_s"]
        else:
            t_rep = None
        per = (t / c["iterations"]) if c.get("iterations") else None
    print("\n[[row]]")
    for k in ("leg", "size_n", "n_edges", "config", "device", "dtype"):
        v = c[k]
        print(f'{k} = {v!r}'.replace("'", '"'))
    print(f'kind = "{kind}"')
    print(f"solve_s = {t:.3f}")
    if kind == "full" and t_rep is not None:
        print(f"timed_rep_solve_s = {t_rep:.3f}")
    print(f"iterations = {c['iterations']}")
    if per is not None and c["iterations"]:
        print(f"s_per_iter = {per:.5f}")
    rr = c.get("residual_rel")
    print(f"residual_rel = {rr}")
    if "recursion_converged" in c:
        print("recursion_converged = true")
    print(f"explicit_converged = {str(c.get('converged')).lower()}")
    acc = c.get("accuracy_rel_l2_vs_direct")
    if acc is not None and acc == acc:
        print(f"accuracy_rel_l2_vs_direct = {acc:.3e}")
    pv = c.get("port_v")
    if pv and pv[0] == pv[0]:
        print(f"port_v = [{pv[0]:.9e}, {pv[1]:.9e}]")
    if c["leg_max_rss_kb"]:
        print(f"leg_process_max_rss_gb = {c['leg_max_rss_kb'] / 1e6:.2f}  # whole test process, all sizes of the leg")
    if c["leg_gpu_peak_mib"] is not None:
        print(f"leg_gpu_peak_mib = {c['leg_gpu_peak_mib']}  # nvidia-smi peak over the whole leg")

pal = d / "palace" / "runs.txt"
if pal.exists():
    print("\n# Palace driven runs (box_palace_driven.sh)")
    for line in pal.read_text().splitlines():
        print(f"# {line}")
