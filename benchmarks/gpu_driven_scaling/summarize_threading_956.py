#!/usr/bin/env python3
"""Write results_threading_956.toml from the issue #956 run tree.

usage: summarize_threading_956.py <run-dir> > results_threading_956.toml

<run-dir> (benchmarks/gpu_driven_scaling/runs/2026-10-09_local_threading_956)
holds the outputs of diag956_threading.rs, one process per leg:

  meta.txt          key = value: measured_date, main_commit, ungated_commit,
                    fix_commit, faer.
  host.txt          cpu, logical_cpus, os (written by sweep956.sh).
  percall/          sweep956.sh, <site>_n<N>_t<T>.stdout (repeat 1).
  percall_refine/   refine956.sh, <site>_n<N>_t<T>_rep<K>.stdout (repeats 2, 3).
                    Per-call legs run the MAIN build: each repeated solve is
                    timed on the ambient parallelism (pool) and under a
                    SequentialSolveScope (seq), in alternating blocks of 20 in
                    one process.
  e2e/              sweep956.sh, <site>_n<N>_<build>_t<T>_rep<K>.stdout.
  e2e_large/        refine956.sh, the same at the largest sizes.
  e2e_gated/        gated956.sh, the same below the size limit.
  spotcheck_faier_0_25_2/
                    spotcheck956.sh: meta.txt (measured_date, tree_commit,
                    faer, build, host_load), gate_off.patch and
                    percall/<site>_n<N>_t8_rep<K>.stdout, the 8-thread
                    per-call legs again on the faier 0.25.2 tree.
                    End-to-end legs run the whole solve on main, on the first
                    fix commit (ungated: a sequential scope at every size) and
                    on the shipped fix (fix: the scope only up to
                    SEQUENTIAL_SOLVE_MAX_DIM unknowns).

T is RAYON_NUM_THREADS, or "default" when it is unset (the rayon pool then
has one thread per logical CPU, which is what faer's default Par::rayon(0)
uses). A leg whose 1-minute load average was above EXCLUDE_LOAD when it
started is listed but left out of every median and ratio summary.

Every number in the output is read from those files or computed from them
here. Pure stdlib; the output depends only on the file contents, so rerunning
it on the committed tree reproduces the committed results file byte for byte.
"""
import pathlib
import re
import statistics
import sys

RUN_DIR = "benchmarks/gpu_driven_scaling/runs/2026-10-09_local_threading_956"
EXCLUDE_LOAD = 100.0
AGREEMENT_TOL = 1e-9
# The AMS fixture's four eigenvalues nearest sigma = -0.5 are the discrete
# gradient null cluster, |lambda| <= 3e-12: zero to round-off. Their own size
# is no scale, so the AMS agreement is measured against |sigma|.
SCALE_FLOOR = {"ams": 0.5}
SITES = ("complex", "ams", "transient")
THREADS = ("1", "8", "default")
d = pathlib.Path(sys.argv[1])


def kv(path):
    out = {}
    for line in path.read_text().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def parse(path):
    """diag956 key=value lines and the value[i] rows of one harness run."""
    text = path.read_text()
    if "test result: ok" not in text:
        raise SystemExit(f"{path.name}: harness run did not pass")
    keys, values = {}, []
    for line in text.splitlines():
        if "diag956 " not in line:
            continue
        line = line[line.index("diag956 ") + len("diag956 "):]
        m = re.match(r"value\[(\d+)\] = (.*)$", line)
        if m:
            values.append([float(x) for x in m.group(2).split()])
            continue
        for tok in line.split():
            if "=" in tok:
                k, v = tok.split("=", 1)
                keys[k] = v
    return keys, values


def max_rel_diff(a, b, floor=0.0):
    """max_i |a_i - b_i| / max(max_i |b_i|, floor) over value rows (complex
    values as 2-vectors)."""
    assert len(a) == len(b), "different value counts"
    norm = lambda v: sum(x * x for x in v) ** 0.5
    scale = max([norm(v) for v in b] + [floor]) or 1.0
    return max(norm([x - y for x, y in zip(u, v)]) for u, v in zip(a, b)) / scale


def tkey(t):
    return THREADS.index(t)


meta = kv(d / "meta.txt")
host = kv(d / "host.txt")
p = print

p("# Issue #956: repeated small sparse triangular solves on the rayon pool.")
p("# GENERATED by benchmarks/gpu_driven_scaling/summarize_threading_956.py from")
p(f"# {RUN_DIR}; do not edit by hand.")
p("#")
p("# Three loops called faer's Lu::solve_in_place once per iteration or step")
p("# with faer's process-global parallelism at its default (every core):")
p("#   complex   eigen/complex/lanczos.rs, the complex shift-invert Lanczos loop")
p("#   ams       eigen/ams.rs lu_solve, the AMS coarse LU solve (Direct coarse")
p("#             solver, and the coarsest level of Amg)")
p("#   transient driven/transient.rs TransientStepper::step, once per time step")
p("# The change that merged runs ams and transient under a SequentialSolveScope")
p("# (Par::Seq), up to sequential_solve_max_dim unknowns.")
p("#")
p("# COMPLEX SITE: MEASURED, NOT SHIPPED. With the scope on the complex Lanczos")
p("# loop, sparse_complex_matches_dense_fixture returned a wrong eigenvalue on")
p("# linux x86-64 CI (issue #1023), so that loop was left as on main. The")
p("# complex rows below are kept as the measurement of that site: build = fix")
p("# and ungated there mean the commits in [meta], which scoped the complex")
p("# loop, not the tree that merged. Everything in this file, including the")
p("# agreement table, was measured on macOS aarch64 only ([hardware]).")
p("#")
p("# HOW TO READ: a developer machine shared with other work. Wall times move")
p("# with the load, so the 1-minute load average is recorded for every leg and")
p(f"# legs started above {EXCLUDE_LOAD:.0f} are excluded from the summaries. In the")
p("# per-call tables pool and seq alternate in blocks of 20 calls inside one")
p("# process, so the two modes of a leg see the same load; the medians are")
p("# over 400 calls per mode (200 steps for transient). cpu_per_call_us is")
p("# (user + sys) CPU over the timed calls divided by the call count.")
p()
p("[meta]")
p("issue = 956")
p(f'measured_date = "{meta["measured_date"]}"')
p(f'main_commit = "{meta["main_commit"]}"')
p(f'ungated_commit = "{meta["ungated_commit"]}"  # scope at every size; superseded')
p(f'fix_commit = "{meta["fix_commit"]}"  # scope up to SEQUENTIAL_SOLVE_MAX_DIM at all three sites; ams and transient shipped so, complex did not')
p('complex_site = "measured, not shipped: linux x86-64 regression, see issue #1023"')
p(f'sequential_solve_max_dim = {meta["sequential_solve_max_dim"]}')
p(f'faer = "{meta["faer"]}"')
p(f'run_dir = "{RUN_DIR}"')
p('generator = "sweep956.sh, refine956.sh, gated956.sh and spotcheck956.sh (in run_dir, in that order), then benchmarks/gpu_driven_scaling/summarize_threading_956.py"')
p('harness = "diag956_threading.rs (in run_dir; an #[ignore] integration test, copied into crates/geode-core/tests/ to build)"')
p(f"exclude_load_above = {EXCLUDE_LOAD:.1f}")
p()
p("[hardware]")
p(f'cpu = "{host["cpu"]}"')
p(f'logical_cpus = {host["logical_cpus"]}')
p(f'os = "{host["os"]}"')
p()

# ---------------------------------------------------------------- per call
rows = []
for sub, rx in (
    ("percall", r"(\w+?)_n(\d+)_t(\w+?)\.stdout$"),
    ("percall_refine", r"(\w+?)_n(\d+)_t(\w+?)_rep(\d+)\.stdout$"),
):
    for f in sorted((d / sub).glob("*.stdout")):
        m = re.match(rx, f.name)
        site, n, t = m.group(1), int(m.group(2)), m.group(3)
        rep = int(m.group(4)) if sub == "percall_refine" else 1
        k, _ = parse(f)
        rows.append((site, n, t, rep, k))
rows.sort(key=lambda r: (SITES.index(r[0]), r[1], tkey(r[2]), r[3]))
excluded = lambda k, key: float(k[key]) > EXCLUDE_LOAD

p("[threading_fix_956]")
p('note = "Per-call cost of each site\'s triangular solve on the MAIN build: the same solve on the ambient parallelism (pool, what main does) and under a SequentialSolveScope (seq, what the fix does). complex: the complex LU of the lossy scalar P1 pencil K(1 + 0.02i) on cube_tet_mesh(n), sigma = 0, as in the Lanczos loop. ams: the real LU of the SPD P1 operator K + 0.5 M, standing in for the nodal coarse operator G^T(K + |sigma|M)G of about the same node count (that operator is not public). transient: TransientStepper::step on the parallel-plate lumped-port fixture of tests/transient_sparams.rs, two steppers advanced in lockstep, one per mode; dofs counts interior edges. threads = RAYON_NUM_THREADS (default = unset)."')
p()
for site, n, t, rep, k in rows:
    dofs = k.get("dofs") or k.get("interior_edges")
    pw, sw = float(k["pool_median_wall_us"]), float(k["seq_median_wall_us"])
    pc, sc = float(k["pool_cpu_per_call_us"]), float(k["seq_cpu_per_call_us"])
    p("[[threading_fix_956.per_call]]")
    p(f'site = "{site}"')
    p(f"mesh_n = {n}")
    p(f"dofs = {dofs}")
    p(f'threads = "{t}"')
    p(f"repeat = {rep}")
    p(f'calls_per_mode = {k["pool_calls"]}')
    p(f"pool_median_wall_us = {pw:.1f}")
    p(f"seq_median_wall_us = {sw:.1f}")
    p(f"pool_cpu_per_call_us = {pc:.1f}")
    p(f"seq_cpu_per_call_us = {sc:.1f}")
    p(f"wall_ratio_pool_over_seq = {pw / sw:.2f}")
    p(f"cpu_ratio_pool_over_seq = {pc / sc:.2f}")
    p(f'seq_vs_pool_max_rel_diff = {float(k["seq_vs_pool_max_rel_diff"]):.3e}  # last solution (transient: displacement after the last step)')
    p(f'loadavg_1min = [{k["loadavg_1min_start"]}, {k["loadavg_1min_end"]}]  # start, end of the timed calls')
    if excluded(k, "loadavg_1min_start"):
        p("excluded = true  # started above exclude_load_above")
    p()

# ------------------------------------------------- faier 0.25.2 spot check
spot_dir = d / "spotcheck_faier_0_25_2"
smeta = kv(spot_dir / "meta.txt")
spot = []
for f in sorted((spot_dir / "percall").glob("*.stdout")):
    m = re.match(r"(\w+?)_n(\d+)_t(\w+?)_rep(\d+)\.stdout$", f.name)
    k, _ = parse(f)
    spot.append((m.group(1), int(m.group(2)), m.group(3), int(m.group(4)), k))
spot.sort(key=lambda r: (SITES.index(r[0]), r[1], tkey(r[2]), r[3]))

p("[threading_fix_956.spot_check_faier_0_25_2]")
p('note = "PR #1010 review: every other table in this file was measured on the faier 0.24.4 git pin ([meta].faer); the tree that ships is on crates.io faier 0.25.2. These are the 8-thread per-call legs again on that tree, at sizes either side of sequential_solve_max_dim, three repeats each, same harness and same pool / seq protocol as [[threading_fix_956.per_call]]. The build is tree_commit with gate_off.patch, which sets SEQUENTIAL_SOLVE_MAX_DIM to 0 so that the pool mode of the transient leg is not itself scoped (the complex and ams legs call the LU directly and do not depend on it). The default pool, 1 thread and the end-to-end legs were NOT rerun on 0.25.2."')
p(f'measured_date = "{smeta["measured_date"]}"')
p(f'tree_commit = "{smeta["tree_commit"]}"')
p(f'faer = "{smeta["faer"]}"')
p(f'build = "{smeta["build"]}"')
p(f'host_load = "{smeta["host_load"]}"')
p('run_dir = "' + RUN_DIR + '/spotcheck_faier_0_25_2"')
p('generator = "spotcheck956.sh (in the parent run_dir)"')
p()
for site, n, t, rep, k in spot:
    pw, sw = float(k["pool_median_wall_us"]), float(k["seq_median_wall_us"])
    pc, sc = float(k["pool_cpu_per_call_us"]), float(k["seq_cpu_per_call_us"])
    p("[[threading_fix_956.spot_check_faier_0_25_2.per_call]]")
    p(f'site = "{site}"')
    p(f"mesh_n = {n}")
    p(f'dofs = {k.get("dofs") or k.get("interior_edges")}')
    p(f'threads = "{t}"')
    p(f"repeat = {rep}")
    p(f'calls_per_mode = {k["pool_calls"]}')
    p(f"pool_median_wall_us = {pw:.1f}")
    p(f"seq_median_wall_us = {sw:.1f}")
    p(f"pool_cpu_per_call_us = {pc:.1f}")
    p(f"seq_cpu_per_call_us = {sc:.1f}")
    p(f"wall_ratio_pool_over_seq = {pw / sw:.2f}")
    p(f"cpu_ratio_pool_over_seq = {pc / sc:.2f}")
    p(f'seq_vs_pool_max_rel_diff = {float(k["seq_vs_pool_max_rel_diff"]):.3e}')
    p(f'loadavg_1min = [{k["loadavg_1min_start"]}, {k["loadavg_1min_end"]}]  # start, end of the timed calls')
    if excluded(k, "loadavg_1min_start"):
        p("excluded = true  # started above exclude_load_above")
    p()

p("[threading_fix_956.spot_check_faier_0_25_2.summary]")
p('note = "Median over the three repeats of pool / seq (> 1 means sequential is cheaper), next to the median of the 0.24.4 legs of the same site, size and thread count where one exists (-1.0 otherwise). dofs is the system dimension the size limit is compared with."')
for site in SITES:
    rs = [r for r in spot if r[0] == site and not excluded(r[4], "loadavg_1min_start")]
    if not rs:
        continue
    sizes = sorted({r[1] for r in rs})
    def smed(src, n, a, b):
        v = [float(r[4][a]) / float(r[4][b]) for r in src if r[0] == site and r[1] == n and r[2] == "8" and not excluded(r[4], "loadavg_1min_start")]
        return f"{statistics.median(v):.2f}" if v else "null"
    dofs = [next(r[4].get("dofs") or r[4].get("interior_edges") for r in rs if r[1] == n) for n in sizes]
    p(f"{site}_t8_mesh_n = {sizes}")
    p(f"{site}_t8_dofs = [{', '.join(dofs)}]")
    for what, a, b in (("wall", "pool_median_wall_us", "seq_median_wall_us"), ("cpu", "pool_cpu_per_call_us", "seq_cpu_per_call_us")):
        new = [smed(spot, n, a, b) for n in sizes]
        old = [smed(rows, n, a, b) for n in sizes]
        p(f"{site}_t8_{what}_ratio = [{', '.join(new)}]")
        if "null" not in old:
            p(f"{site}_t8_{what}_ratio_faier_0_24_4 = [{', '.join(old)}]")
        else:
            p(f"{site}_t8_{what}_ratio_faier_0_24_4 = [{', '.join(x if x != 'null' else '-1.0' for x in old)}]  # -1.0: size not measured on 0.24.4")
p()

# ---------------------------------------------------------------- end to end
e2e = {}
BUILDS = ("main", "ungated", "fix")
for sub in ("e2e", "e2e_large", "e2e_gated"):
    for f in sorted((d / sub).glob("*.stdout")):
        m = re.match(r"(\w+?)_n(\d+)_(main|ungated|fix)_t(\w+?)_rep(\d+)\.stdout$", f.name)
        site, n, build, t, rep = m.group(1), int(m.group(2)), m.group(3), m.group(4), int(m.group(5))
        e2e[(site, n, build, t, rep)] = parse(f)
ekey = lambda t: (SITES.index(t[0]), t[1], tkey(t[3]), t[4], BUILDS.index(t[2]))
tag_of = lambda site: "run" if site == "transient" else "solve"

p("[threading_fix_956.end_to_end]")
p('note = "The whole solve on main, ungated (the first fix commit: sequential at every size) and fix (meta.fix_commit: sequential up to sequential_solve_max_dim unknowns; shipped for ams and transient, not for complex, see the header), one process per leg. Above the limit fix takes no scope, so it runs as main does and was not rerun there; below it fix and ungated make the same change. complex: SparseComplexShiftInvertLanczos::default().smallest_eigenpairs (20 modes) on the lossy P1 pencil; timed region = factorization + Lanczos loop. ams: matrix-free shift-invert Lanczos with the three-space AMS inner preconditioner and GEODE_COARSE=direct, on the synthetic transmon cavity of tests/transmon_eigenmode.rs (4 modes, sigma = -0.5); timed region = the eigensolve. transient: TransientSolver::run (400 steps at mesh_n 16, 200 at 24) of generalized-alpha (rho_inf = 1) on the parallel-plate lumped-port fixture; timed region = run (factorization + steps), factor_* = one factorization alone. *_user_s and *_sys_s are getrusage deltas around the timed region."')
p()
for key in sorted(e2e, key=ekey):
    site, n, build, t, rep = key
    k, values = e2e[key]
    tag = tag_of(site)
    p("[[threading_fix_956.end_to_end.run]]")
    p(f'site = "{site}"')
    p(f"mesh_n = {n}")
    p(f'dofs = {k.get("dofs") or k.get("interior_edges")}')
    p(f'build = "{build}"')
    p(f'threads = "{t}"')
    p(f"repeat = {rep}")
    if site == "transient":
        for x in ("user", "sys", "wall"):
            p(f'factor_{x}_s = {k["factor_" + x + "_s"]}')
    for x in ("user", "sys", "wall"):
        p(f'{tag}_{x}_s = {k[tag + "_" + x + "_s"]}')
    if "inner_iters" in k:
        p(f'inner_iters = {k["inner_iters"]}')
    p(f'loadavg_1min = [{k["loadavg_1min_process_start"]}, {k["loadavg_1min_process_end"]}]  # process start, end')
    p(f"n_values = {len(values)}")
    if excluded(k, "loadavg_1min_process_start"):
        p("excluded = true  # started above exclude_load_above")
    p()

# ---------------------------------------------------------------- agreement
p("[threading_fix_956.agreement]")
p(f'note = "max_i |x_i - main_i| / max_i |main_i| over the returned values (eigenvalues; transient: every V(t) sample of the excited port), x = ungated or fix, same size, thread count and repeat; the worst over repeats. main_thread_spread compares main at RAYON_NUM_THREADS=1 with main at 8 threads, the round-off floor already present on main. ams: the four values are the discrete gradient null cluster (|lambda| <= 3e-12, zero to round-off), so the denominator there is max(max_i |main_i|, |sigma| = 0.5); the inner iteration count is identical on every build. tolerance = {AGREEMENT_TOL:.0e} on every *_vs_main value. Load does not enter here, so excluded legs are compared too. Platform: macOS aarch64 only ([hardware]). On linux x86-64 the complex site did not agree: with the scope, sparse_complex_matches_dense_fixture returned a wrong first eigenvalue in CI (issue #1023), and the complex scope was not shipped. The complex_* rows are that unshipped change."')
worst = 0.0
for site, n in sorted({(k[0], k[1]) for k in e2e}, key=lambda s: (SITES.index(s[0]), s[1])):
    for t in sorted({k[3] for k in e2e if k[:2] == (site, n)}, key=tkey):
        for build in ("ungated", "fix"):
            diffs = [
                max_rel_diff(e2e[(site, n, build, t, r)][1], e2e[(site, n, "main", t, r)][1], SCALE_FLOOR.get(site, 0.0))
                for r in (1, 2)
                if (site, n, build, t, r) in e2e and (site, n, "main", t, r) in e2e
            ]
            if diffs:
                worst = max([worst] + diffs)
                p(f"{site}_n{n}_t{t}_{build}_vs_main_max_rel_diff = {max(diffs):.3e}")
    a, b = e2e.get((site, n, "main", "1", 1)), e2e.get((site, n, "main", "8", 1))
    if a and b:
        p(f"{site}_n{n}_main_thread_spread_t1_vs_t8_max_rel_diff = {max_rel_diff(a[1], b[1], SCALE_FLOOR.get(site, 0.0)):.3e}")
p(f"tolerance = {AGREEMENT_TOL:.0e}")
p(f"all_within_tolerance = {'true' if worst <= AGREEMENT_TOL else 'false'}")
p()

# ---------------------------------------------------------------- summary
p("[threading_fix_956.summary]")
p('note = "Medians over the non-excluded repeats. Per call: pool / seq, so > 1 means sequential is cheaper. End to end: [main, ungated or fix] user + sys CPU and wall seconds of the timed region."')
for site in SITES:
    for t in THREADS:
        rs = [r for r in rows if r[0] == site and r[2] == t and not excluded(r[4], "loadavg_1min_start")]
        if not rs:
            continue
        sizes = sorted({r[1] for r in rs})
        def med(n, a, b):
            return statistics.median(float(r[4][a]) / float(r[4][b]) for r in rs if r[1] == n)
        cpu = [med(n, "pool_cpu_per_call_us", "seq_cpu_per_call_us") for n in sizes]
        wall = [med(n, "pool_median_wall_us", "seq_median_wall_us") for n in sizes]
        p(f"per_call_{site}_t{t}_mesh_n = {sizes}")
        p(f"per_call_{site}_t{t}_cpu_ratio = [{', '.join(f'{x:.2f}' for x in cpu)}]")
        p(f"per_call_{site}_t{t}_wall_ratio = [{', '.join(f'{x:.2f}' for x in wall)}]")
for site, n in sorted({(k[0], k[1]) for k in e2e}, key=lambda s: (SITES.index(s[0]), s[1])):
    tag = tag_of(site)
    for t in THREADS:
        def med(build, what):
            vals = [
                sum(float(k[f"{tag}_{x}_s"]) for x in what)
                for (s, nn, b, tt, _), (k, _) in e2e.items()
                if (s, nn, b, tt) == (site, n, build, t) and not excluded(k, "loadavg_1min_process_start")
            ]
            return statistics.median(vals) if vals else None
        for build in ("ungated", "fix"):
            cm, cf = med("main", ("user", "sys")), med(build, ("user", "sys"))
            wm, wf = med("main", ("wall",)), med(build, ("wall",))
            if None not in (cm, cf, wm, wf):
                p(f"end_to_end_{site}_n{n}_t{t}_{build}_cpu_s = [{cm:.3f}, {cf:.3f}]")
                p(f"end_to_end_{site}_n{n}_t{t}_{build}_wall_s = [{wm:.3f}, {wf:.3f}]")
