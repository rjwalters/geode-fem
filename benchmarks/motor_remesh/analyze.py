#!/usr/bin/env python3
"""Tables of the remesh-and-transfer validation (issue #1184).

    python3 -I benchmarks/motor_remesh/analyze.py

Reads ``runs/path_L*.json`` and ``runs/identity_L*.json`` (written by
``icem_remesh_path``) and writes ``tables.md``. Standard library only.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = HERE / "runs"


def load(name):
    p = RUNS / name
    return json.loads(p.read_text()) if p.exists() else None


def g(x, f="{:.3e}"):
    return "–" if x is None else f.format(x)


def path_table(d, label):
    out = [f"### Path, {label}\n",
           "| t | generation | event | min angle (deg) | F (N² m²) | dF/dt | mean(1) (N m) | "
           "Newton its | solve (s) | total (s) |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in d["path"]:
        ev = r["event"]
        tag = "–" if ev is None else (
            f"{ev['trigger']['kind']} ({g(ev['trigger'].get('min_angle_deg'), '{:.2f}')}°): "
            f"gmsh {ev['mesh_s']:.2f} s, setup {ev['setup_s']:.2f} s")
        its = sum(c["newton_iterations"] for c in r["currents"])
        out.append(f"| {r['t']:.1f} | {r['generation']} | {tag} | "
                   f"{g(r['quality']['min_angle_deg'], '{:.2f}')} | {r['F']:.6e} | "
                   f"{r['dF_dt']:.6e} | {r['currents'][-1]['mean']:.6f} | {its} | "
                   f"{r['solve_s']:.1f} | {r['total_s']:.1f} |")
    return "\n".join(out) + "\n"


def jump_rows(j, name):
    loaded = j["currents"][-1]
    cog = j["currents"][0]
    return (f"| {name} | {j['nodes_a']} → {j['nodes_b']} | "
            f"{g(j['min_angle_a'], '{:.2f}')} → {g(j['min_angle_b'], '{:.2f}')} | "
            f"{j['F_rel']:.2e} | {j['dF_dt_rel']:.2e} | {j['grad_F_rel_norm_diff']:.2e} | "
            f"{j['grad_F_cosine']:.7f} | {loaded['mean_diff']:+.2e} | {loaded['std_rel']:.2e} | "
            f"{cog['std_rel']:.2e} |")


def main():
    parts = ["# Remesh-and-transfer validation: tables\n",
             "Generated by `analyze.py` from `runs/`. Model: h45 coupling torque, g20, "
             "currents 0, 0.5, 1 of 9.6777 A (fixed peak current), Newton `rel_tol = 1e-12`, "
             "control-point space (22 components).\n"]
    for name in sorted(RUNS.glob("identity_L*.json")):
        d = json.loads(name.read_text())
        parts.append(f"### Bit-identity, L{d['level']}\n")
        parts.append("| start | point | values compared | bit-identical |\n|---|---|---|---|")
        for r in d["comparisons"]:
            parts.append(f"| {r['warm']} | {r['point']} | {r['values']} | {r['bit_identical']} |")
        parts.append("")
    runs = [(f, load(f)) for f in ("path_L1.json", "path_L1_cold.json", "path_L2.json")]
    runs = [(f, d) for f, d in runs if d]
    for f, d in runs:
        parts.append(path_table(d, f"L{d['level']}, start {d['model']['warm']} (`{f}`)"))
    parts.append("### Jumps moved → fresh at the same design\n")
    parts.append("`F rel` = |F_fresh − F_moved| / F_moved; gradient columns are for dF/dθ over all "
                 "22 components; `mean(1)` is the full-current mean torque.\n")
    parts.append("| case | nodes | min angle (deg) | F rel | dF/dt rel | ‖ΔdF‖/‖dF‖ | cos(dF) | "
                 "Δ mean(1) (N m) | std(1) rel | std(0) rel |")
    parts.append("|---|---|---|---|---|---|---|---|---|---|")
    for f, d in runs:
        L = d["level"]
        for gp in d["gaps"]:
            if "gap" in gp:
                parts.append(jump_rows(gp["gap"], f"L{L} gap at {gp['design']} ({f})"))
        for e in d["events"]:
            parts.append(jump_rows(e["jump_moved_to_fresh"], f"L{L} event t = {e['t']:.1f} ({f})"))
    parts.append("")
    parts.append("### Central differences next to the event\n")
    parts.append("Directional: along θ(t), steps in t. Components: step 1e-6 m. `rel` is "
                 "|FD − adjoint| / |adjoint|.\n")
    parts.append("| run | point | t | generation | min angle (deg) | dF/dt rel (h=1e-3) | "
                 "dF/dt rel (h=1e-4) | dmean1/dt rel (h=1e-4) | components rel (max) |")
    parts.append("|---|---|---|---|---|---|---|---|---|")
    for f, d in runs:
        for e in d["events"]:
            for key in ("fd_before", "fd_after"):
                b = e[key]
                dr = {x["h_t"]: x for x in b["directional"]}
                comps = ", ".join(f"{c['component']} {c['rel_err']:.1e}" for c in b["components"])
                parts.append(f"| `{f}` | {b['label']} | {b['t_point']:.2f} | {b['generation']} | "
                             f"{g(b['quality']['min_angle_deg'], '{:.2f}')} | "
                             f"{dr[1e-3]['rel_err_F']:.1e} | {dr[1e-4]['rel_err_F']:.1e} | "
                             f"{dr[1e-4]['rel_err_mean1']:.1e} | {comps} |")
    parts.append("")
    parts.append("### Warm start at the event\n")
    parts.append("| run | start | extrapolated nodes | F rel (path vs cold) | Newton its path | "
                 "Newton its cold |")
    parts.append("|---|---|---|---|---|---|")
    for f, d in runs:
        for e in d["events"]:
            w = e["warm_vs_cold_at_event"]
            s = w["start"]
            parts.append(f"| `{f}` | {s['kind']} | {s.get('extrapolated_nodes', '–')} | "
                         f"{w['F_rel']:.1e} | {w['newton_iterations_warm']} | "
                         f"{w['newton_iterations_cold']} |")
    parts.append("")
    (HERE / "tables.md").write_text("\n".join(parts) + "\n")
    print(f"wrote {HERE / 'tables.md'}")


if __name__ == "__main__":
    main()
