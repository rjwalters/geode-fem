"""Summarise study.json (issue #1174) into summary.md.

O(h^2) window: the longest contiguous run of steps around h = 1e-5 m over
which remainder / h^2 stays within a factor 2 of its value at h = 1e-5 m.
The window is reported with its width in decades of h and the range of the
local observed order inside it. Run: python3 -I analyze.py
"""

import json
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
D = json.loads((HERE / "study.json").read_text())
MODES = {"conforming": "conforming / Arkkio", "h45": "h45 / coupling torque",
         "h45arkkio": "h45 / Arkkio"}


def window(rows, h_ref=1e-5, factor=2.0):
    hs = [r["h"] for r in rows]
    c = [r["remainder"] / r["h"] ** 2 for r in rows]
    i0 = min(range(len(hs)), key=lambda i: abs(math.log(hs[i] / h_ref)))
    ok = [c[i] / c[i0] <= factor and c[i0] / c[i] <= factor for i in range(len(c))]
    lo = hi = i0
    while lo > 0 and ok[lo - 1]:
        lo -= 1
    while hi < len(c) - 1 and ok[hi + 1]:
        hi += 1
    orders = [rows[i]["order_to_next"] for i in range(lo, hi)]
    dec = math.log10(hs[lo] / hs[hi])
    return hs[lo], hs[hi], dec, min(orders), max(orders), c[i0]


out = []
w = out.append
w("# Summary of study.json (generated by analyze.py)\n")
w("O(h^2) window: contiguous steps around h = 1e-5 m with remainder/h^2 within a "
  "factor 2 of its value at 1e-5 m; orders are the local observed orders inside it.\n")
for section, key in [("Taylor at X0, off-band velocity", "taylor"),
                     ("Taylor at the second design X1", "design2_taylor"),
                     ("Taylor with band-moving velocity", "band_taylor")]:
    w(f"## {section}\n")
    w("| mode | current | objective | h window (m) | decades | local order range | remainder/h^2 at 1e-5 |")
    w("|---|---|---|---|---|---|---|")
    n_rows = n_five = 0
    for mk, mname in MODES.items():
        if mk not in D["modes"]:
            continue
        for lev, c in D["modes"][mk]["currents"].items():
            for obj in ["mean", "std"]:
                rows = c[f"{key}_{obj}"]
                hi, lo, dec, omin, omax, c5 = window(rows)
                n_rows += 1
                n_five += dec >= 5.0 - 1e-9
                w(f"| {mname} | {lev} | {obj} | {hi:.0e} .. {lo:.0e} | {dec:.1f} | "
                  f"{omin:.2f} .. {omax:.2f} | {c5:.3e} |")
    w(f"\n{n_five} of {n_rows} windows span at least 5 decades.\n")
w("## Central-difference step sweep: best relative error vs the adjoint\n")
w("| mode | current | mean: adjoint dJ.V | mean: best rel. err (h) | std: adjoint dJ.V | std: best rel. err (h) |")
w("|---|---|---|---|---|---|")
for mk, mname in MODES.items():
    if mk not in D["modes"]:
        continue
    for lev, c in D["modes"][mk]["currents"].items():
        b = c["fd_best"]
        w(f"| {mname} | {lev} | {b['mean']['adjoint']:+.6e} | {b['mean']['rel_err']:.1e} ({b['mean']['h']:.0e}) | "
          f"{b['std']['adjoint']:+.6e} | {b['std']['rel_err']:.1e} ({b['std']['h']:.0e}) |")
w("")
w("## Gradient vs Newton rel_tol (max relative change from rel_tol = 1e-14 over 3 velocities)\n")
tols = None
for mk, mname in MODES.items():
    if mk not in D["modes"]:
        continue
    for lev, c in D["modes"][mk]["currents"].items():
        if tols is None:
            tols = [t["rel_tol"] for t in c["tolerance"]]
            w("| mode | current | objective | " + " | ".join(f"{t:.0e}" for t in tols) + " |")
            w("|---|---|---|" + "---|" * len(tols))
        for obj in ["mean", "std"]:
            w(f"| {mname} | {lev} | {obj} | " + " | ".join(
                f"{t[obj + '_max_rel_change']:.1e}" for t in c["tolerance"]) + " |")
w("")
w("## Noise floor and cost\n")
w("| mode | current | noise: max dT | noise: mean | noise: std | forward 10 angles (s) | adjoint 10 angles (s) | ratio | cold forward (s, its) | cold adjoint (s) | cold ratio |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for mk, mname in MODES.items():
    if mk not in D["modes"]:
        continue
    for lev, c in D["modes"][mk]["currents"].items():
        n = c["noise_floor"]
        k = c["cost"]
        w(f"| {mname} | {lev} | {n['max_torque']:.1e} | {n['mean']:.1e} | {n['std']:.1e} | "
          f"{k['forward_total']:.3f} | {k['adjoint_total']:.3f} | {k['ratio']:.3f} | "
          f"{k['cold_forward']:.3f} ({k['cold_newton_its']}) | {k['cold_adjoint']:.3f} | {k['cold_ratio']:.3f} |")
w("")
w("## Base design\n")
w("| mode | current | mean (N m) | std (N m) | max iron |B| (T) | round-off-floor solves |")
w("|---|---|---|---|---|---|")
for mk, mname in MODES.items():
    if mk not in D["modes"]:
        continue
    for lev, c in D["modes"][mk]["currents"].items():
        w(f"| {mname} | {lev} | {c['mean']:.9f} | {c['std']:.9f} | {c['iron_b_max']:.3f} | "
          f"{c['roundoff_floor_solves']} / 10 |")
(HERE / "summary.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
